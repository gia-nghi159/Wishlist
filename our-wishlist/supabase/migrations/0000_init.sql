-- 1. Enable Extensions
CREATE EXTENSION IF NOT EXISTS vector WITH SCHEMA public;

-- =========================================================================
-- 2. TABLE DEFINITIONS
-- =========================================================================

-- Groups table
CREATE TABLE IF NOT EXISTS groups (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  name TEXT NOT NULL,
  created_by TEXT, -- Clerk User ID (Set to NULL on user deletion)
  created_at TIMESTAMPTZ DEFAULT now()
);

-- Group members table
CREATE TABLE IF NOT EXISTS group_members (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  group_id UUID REFERENCES groups(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL, -- Clerk User ID
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(group_id, user_id)
);

-- Profiles table
CREATE TABLE IF NOT EXISTS profiles (
  user_id TEXT PRIMARY KEY,
  preferred_unit TEXT DEFAULT 'Inches',
  
  -- Measurements
  height TEXT,
  weight TEXT,
  chest TEXT,
  waist TEXT,
  inseam TEXT,
  
  -- Quick sizes
  shoe_size TEXT,
  ring_size TEXT,
  preferred_fit TEXT,
  
  -- Aesthetics
  metal_preference TEXT,
  favorite_brands TEXT,
  dealbreakers TEXT,
  style_words TEXT,
  notes TEXT,
  
  -- Embeddings
  style_embedding vector(768),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Wishes table
CREATE TABLE IF NOT EXISTS wishes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT timezone('utc'::text, now()) NOT NULL,
  name TEXT NOT NULL,
  description TEXT,
  url TEXT,
  image_url TEXT,
  is_inspo BOOLEAN DEFAULT false,
  user_id TEXT NOT NULL, -- Clerk User ID (The owner)
  group_id UUID REFERENCES groups(id) ON DELETE CASCADE,
  reserved_by TEXT, -- Clerk User ID of the reserver (NULL if available)
  item_embedding vector(768), -- Embeddings
  price NUMERIC(10, 2) -- Target amount for group funding
);

-- Contributions Table (Ledger for fractional gifting)
CREATE TABLE IF NOT EXISTS contributions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  wish_id BIGINT REFERENCES wishes(id) ON DELETE CASCADE,
  user_id TEXT NOT NULL, -- Clerk User ID
  amount NUMERIC(10, 2) NOT NULL CHECK (amount > 0),
  created_at TIMESTAMPTZ DEFAULT now()
);

-- =========================================================================
-- 3. ROW LEVEL SECURITY (RLS) POLICIES
-- =========================================================================

-- Enable RLS on all structural tables
ALTER TABLE groups ENABLE ROW LEVEL SECURITY;
ALTER TABLE group_members ENABLE ROW LEVEL SECURITY;
ALTER TABLE profiles ENABLE ROW LEVEL SECURITY;
ALTER TABLE wishes ENABLE ROW LEVEL SECURITY;
ALTER TABLE contributions ENABLE ROW LEVEL SECURITY;

-- ---------------------------------------------------------
-- Profiles Policies
-- ---------------------------------------------------------
CREATE POLICY "Allow authenticated to view profiles" ON profiles 
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Users can insert own profile" ON profiles 
  FOR INSERT TO authenticated WITH CHECK (user_id = (auth.jwt() ->> 'sub'));

CREATE POLICY "Users can update own profile" ON profiles 
  FOR UPDATE TO authenticated USING (user_id = (auth.jwt() ->> 'sub'));

-- ---------------------------------------------------------
-- Groups Policies
-- ---------------------------------------------------------
CREATE POLICY "Allow group creation" ON groups 
  FOR INSERT TO authenticated WITH CHECK (true);

CREATE POLICY "Allow members to view group info" ON groups 
  FOR SELECT TO authenticated USING (
    EXISTS (
      SELECT 1 FROM group_members 
      WHERE group_members.group_id = groups.id 
      AND group_members.user_id = (auth.jwt() ->> 'sub')
    )
  );

-- ---------------------------------------------------------
-- Group Members Policies
-- ---------------------------------------------------------
CREATE POLICY "Allow members to join a group" ON group_members 
  FOR INSERT TO authenticated WITH CHECK (user_id = (auth.jwt() ->> 'sub'));

CREATE POLICY "Allow reading group members" ON group_members 
  FOR SELECT TO authenticated USING (true);

CREATE POLICY "Allow members to view their memberships" ON group_members 
  FOR SELECT TO authenticated USING (user_id = (auth.jwt() ->> 'sub'));

-- ---------------------------------------------------------
-- Wishes Policies
-- ---------------------------------------------------------
-- Allow users to read wishes
CREATE POLICY "Allow users to select wishes" ON wishes 
  FOR SELECT TO authenticated USING (true);

-- Allow users to create wishes
CREATE POLICY "Allow users to insert wishes" ON wishes 
  FOR INSERT TO authenticated WITH CHECK (user_id = (auth.jwt() ->> 'sub'));

-- Allow users to delete their own wishes
CREATE POLICY "Allow users to delete own wishes" ON wishes 
  FOR DELETE TO authenticated USING (user_id = (auth.jwt() ->> 'sub'));

-- Allow group members to update wishes (specifically to lock reservations)
CREATE POLICY "Allow group members to update locks" ON wishes
  FOR UPDATE TO authenticated
  USING (true)
  WITH CHECK (true);

-- ---------------------------------------------------------
-- Contributions Policies
-- ---------------------------------------------------------
-- Allow users to see all contributions for transparency
CREATE POLICY "Allow authenticated to read contributions" ON contributions 
  FOR SELECT TO authenticated USING (true);

-- Allow users to make a contribution
CREATE POLICY "Allow authenticated to insert contributions" ON contributions 
  FOR INSERT TO authenticated WITH CHECK (user_id = (auth.jwt() ->> 'sub'));

