-- Match wishes RPC
CREATE OR REPLACE FUNCTION match_wishes (
  query_embedding vector(768),
  match_threshold float,
  match_count int,
  p_group_id uuid,
  p_user_id text
)
RETURNS TABLE (
  id bigint,
  name text,
  description text,
  url text,
  is_inspo boolean,
  similarity float
)
LANGUAGE sql
AS $$
  SELECT
    wishes.id,
    wishes.name,
    wishes.description,
    wishes.url,
    wishes.is_inspo,
    1 - (wishes.item_embedding <=> query_embedding) AS similarity
  FROM wishes
  WHERE 1 - (wishes.item_embedding <=> query_embedding) > match_threshold
    AND wishes.group_id = p_group_id
    AND wishes.user_id = p_user_id
  ORDER BY wishes.item_embedding <=> query_embedding
  LIMIT match_count;
$$;

-- Reservation RPC
CREATE OR REPLACE FUNCTION reserve_wish_atomic(p_wish_id bigint, p_user_id text)
RETURNS wishes AS $$
DECLARE
  result wishes;
BEGIN
  UPDATE wishes
  SET reserved_by = p_user_id
  WHERE id = p_wish_id AND reserved_by IS NULL
  RETURNING * INTO result;
  
  IF NOT FOUND THEN
    RAISE EXCEPTION 'ALREADY_RESERVED';
  END IF;
  
  RETURN result;
END;
$$ LANGUAGE plpgsql;

-- Contribute to Wish RPC (Atomic Ledger Transaction)
CREATE OR REPLACE FUNCTION contribute_to_wish(p_wish_id bigint, p_user_id text, p_amount numeric)
RETURNS json AS $$
DECLARE
  v_wish wishes;
  v_current_total numeric;
  v_new_total numeric;
BEGIN
  -- Lock the specific wish row for update to prevent race conditions
  SELECT * INTO v_wish FROM wishes WHERE id = p_wish_id FOR UPDATE;
  
  IF NOT FOUND THEN
    RAISE EXCEPTION 'Wish not found';
  END IF;

  IF v_wish.price IS NULL THEN
    RAISE EXCEPTION 'Cannot contribute to an item without a price';
  END IF;

  IF v_wish.reserved_by IS NOT NULL THEN
    RAISE EXCEPTION 'Item is already fully reserved or funded';
  END IF;

  -- Calculate current total contributions
  SELECT COALESCE(SUM(amount), 0) INTO v_current_total 
  FROM contributions 
  WHERE wish_id = p_wish_id;

  v_new_total := v_current_total + p_amount;

  -- Check if contribution exceeds price
  IF v_new_total > v_wish.price THEN
    RAISE EXCEPTION 'Contribution exceeds the target price. Remaining amount needed: %', (v_wish.price - v_current_total);
  END IF;

  -- Insert contribution
  INSERT INTO contributions (wish_id, user_id, amount)
  VALUES (p_wish_id, p_user_id, p_amount);

  -- If fully funded, lock the wish
  IF v_new_total = v_wish.price THEN
    UPDATE wishes SET reserved_by = 'GROUP_FUNDED' WHERE id = p_wish_id;
    v_wish.reserved_by := 'GROUP_FUNDED';
  END IF;

  -- Return updated status
  RETURN json_build_object(
    'new_total', v_new_total,
    'price', v_wish.price,
    'is_funded', (v_new_total = v_wish.price)
  );
END;
$$ LANGUAGE plpgsql;

-- User data deletion RPC
CREATE OR REPLACE FUNCTION delete_user_data(p_user_id text)
RETURNS void AS $$
BEGIN
  DELETE FROM wishes WHERE user_id = p_user_id;
  DELETE FROM group_members WHERE user_id = p_user_id;
  DELETE FROM profiles WHERE user_id = p_user_id;
  -- Nullify creator for user-created groups
  UPDATE groups SET created_by = NULL WHERE created_by = p_user_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- Cascade Group Deletion RPC
CREATE OR REPLACE FUNCTION delete_group_data(p_group_id uuid)
RETURNS void AS $$
BEGIN
  DELETE FROM wishes WHERE group_id = p_group_id;
  DELETE FROM group_members WHERE group_id = p_group_id;
  DELETE FROM groups WHERE id = p_group_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

